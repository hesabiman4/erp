test('phone invoice cards, location scope, modal footer and English direction',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await expect(page.locator('.location-select')).toBeVisible();
  await page.screenshot({path:`${evidence}/redesign-mobile.png`,fullPage:true});
  await page.locator('.task-launchers button').filter({hasText:'فروش جدید'}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  const footer=page.locator('.sale-form>.form-footer');
  await expect(footer).toBeInViewport();
  await page.locator('input[name=paid]').fill('0');
  await expect(footer).toBeInViewport();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:`${evidence}/redesign-mobile-sale.png`});
  await page.locator('[role=dialog] button[aria-label="بستن"]').click();
  await page.locator('.menu-toggle').click();
  await page.locator('.sidebar a[href="/sales"]').click();
  await expect(page.locator('.interactive-table tbody tr').first()).toBeVisible();
  const visibleAmount=page.locator('.interactive-table tbody tr').first().locator('td[data-label="مبلغ"]');
  await expect(visibleAmount).toBeVisible();
  await visibleAmount.scrollIntoViewIfNeeded();
  expect(await page.locator('.interactive-table tbody tr').first().locator('td').evaluateAll(cells=>cells.every(cell=>cell.scrollWidth<=cell.clientWidth+1))).toBe(true);
  await page.screenshot({path:`${evidence}/redesign-mobile-invoices.png`});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.locator('.language-select').selectOption('en');
  await expect(page.locator('html')).toHaveAttribute('dir','ltr');
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('/');
  await expect(page.locator('.today-work')).toBeVisible();
  await expect(page.locator('.loading')).toHaveCount(0,{timeout:60000});
  await expect(page.locator('.task-launchers button').first()).toContainText('New sale');
  await page.screenshot({path:`${evidence}/redesign-english.png`});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
