import {closeDocumentOrDialog} from './navigation';
import {test,expect} from '@playwright/test';
import {readFile,mkdir} from 'node:fs/promises';

// Review tests read the configured database and only submit authentication.
const evidence=process.env.ERP_E2E_OUTPUT||'../.local/design/e2e';
test.setTimeout(120000);
test.beforeEach(async({page})=>{
  const credentials=JSON.parse(await readFile(process.env.ERP_E2E_CREDENTIALS||'../.local/demo-credentials.json','utf8'));
  await page.goto('/');
  await page.locator('input[name=username]').fill('owner');
  await page.locator('input[name=password]').fill(credentials.owner);
  const login=page.waitForResponse(r=>r.url().endsWith('/api/session/')&&r.request().method()==='POST');
  await page.locator('button[type=submit]').click();
  expect((await login).status()).toBe(200);
  await expect(page.locator('.today-work')).toBeVisible({timeout:60000});
  await expect(page.locator('.metric-value').first()).toBeVisible({timeout:60000});
  await expect(page.locator('.loading')).toHaveCount(0,{timeout:60000});
  await mkdir(evidence,{recursive:true});
});

